/* Builds src/data/rankings.json — tiered PPR positional rankings (QB/RB/WR/TE)
   from ESPN's public projection data. No auth needed; the player universe is
   public even though the league is private.
   Run: npm run rankings   (also part of `npm run refresh`) */

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { SEASON, LEAGUE_ID, PRO_TEAM, POSITION } from './lib/espn.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '../src/data/rankings.json');

const KEEP = ['QB', 'RB', 'WR', 'TE'];
const PER_POS = 40;

const HEADERS = {
  'User-Agent': 'Mozilla/5.0 (compatible; ArmchairQuarterbacksBot/1.0)',
  Accept: 'application/json',
};

/** x-fantasy-filter: skill-position players, ordered by ESPN's PPR draft rank. */
const FILTER = {
  players: {
    filterSlotIds: { value: [0, 2, 4, 6] },
    sortDraftRanks: { sortPriority: 100, sortAsc: true, value: 'PPR' },
    limit: 320,
    offset: 0,
  },
};

async function fetchPlayers() {
  // league-scoped endpoint works because the league is public; it carries
  // projections + draft ranks that the bare /players endpoint omits.
  const url = `https://lm-api-reads.fantasy.espn.com/apis/v3/games/ffl/seasons/${SEASON}/segments/0/leagues/${LEAGUE_ID}?view=kona_player_info`;
  const res = await fetch(url, {
    headers: { ...HEADERS, 'x-fantasy-filter': JSON.stringify(FILTER) },
  });
  if (!res.ok) throw new Error(`kona_player_info ${res.status}`);
  const j = await res.json();
  return j.players || [];
}

/** projected season total: stats entry id "10<season>", season split, projection source */
function projectedTotal(player, seasonId) {
  const want = `10${seasonId}`;
  const s = (player.stats || []).find(
    (x) => x.id === want && x.statSourceId === 1 && x.statSplitTypeId === 0,
  );
  return s?.appliedTotal ?? null;
}

function tierize(rows) {
  // A new tier starts when a player projects meaningfully below the current
  // tier's leader (>7%), or the tier already holds 5. Keeps tiers intuitive.
  if (rows.length < 3) return rows.map((r) => ({ ...r, tier: 1 }));
  let tier = 1;
  let tierTop = rows[0].proj ?? 0;
  let count = 0;
  return rows.map((r, i) => {
    if (i > 0) {
      count++;
      const p = r.proj ?? 0;
      const dropPct = tierTop > 0 ? (tierTop - p) / tierTop : 0;
      if (dropPct > 0.07 || count >= 5) {
        tier++;
        tierTop = p;
        count = 0;
      }
    }
    return { ...r, tier };
  });
}

async function main() {
  const players = await fetchPlayers();
  const byPos = { QB: [], RB: [], WR: [], TE: [] };

  for (const entry of players) {
    const p = entry.player || entry;
    const pos = POSITION[p.defaultPositionId];
    if (!KEEP.includes(pos)) continue;
    const proj = projectedTotal(p, SEASON);
    byPos[pos].push({
      name: p.fullName,
      team: PRO_TEAM[p.proTeamId] ?? 'FA',
      proj: proj != null ? Number(proj.toFixed(1)) : null,
      espnRank: p.draftRanksByRankType?.PPR?.rank ?? null,
      injury: p.injuryStatus && p.injuryStatus !== 'ACTIVE' ? p.injuryStatus : null,
    });
  }

  const positions = {};
  for (const pos of KEEP) {
    let rows = byPos[pos]
      .filter((r) => r.proj != null || r.espnRank != null)
      .sort((a, b) => {
        if (a.proj != null && b.proj != null) return b.proj - a.proj;
        return (a.espnRank ?? 999) - (b.espnRank ?? 999);
      })
      .slice(0, PER_POS)
      .map((r, i) => ({ rank: i + 1, ...r }));
    positions[pos] = tierize(rows);
  }

  const out = {
    _comment: 'Auto-generated by scripts/fetch-rankings.mjs from ESPN PPR projections.',
    generatedAt: new Date().toISOString(),
    scoring: 'PPR',
    season: SEASON,
    positions,
  };
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(
    `✓ rankings.json — ` +
    KEEP.map((p) => `${p}:${positions[p].length}`).join(' '),
  );
}

main().catch((e) => {
  console.error('fetch-rankings failed:', e.message);
  process.exitCode = 1;
});
