/* Writes src/data/top-players.json — the top 10 fantasy scorers of the most
   recently completed NFL week (PPR), from ESPN's public player data.
   Safe in the preseason (writes an empty set). Refreshed Mon / Tue / Fri in CI.
   Run: npm run topplayers */

import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { SEASON, LEAGUE_ID, PRO_TEAM, POSITION } from './lib/espn.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '../src/data/top-players.json');

const HEADERS = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/124.0 Safari/537.36',
  Accept: 'application/json',
};

function currentWeek() {
  try {
    const l = JSON.parse(readFileSync(resolve(__dirname, '../src/data/league.json'), 'utf8'));
    return l.league?.currentWeek || 0;
  } catch { return 0; }
}

function emptyOut(week, note) {
  return {
    _comment: 'Auto-generated by scripts/fetch-top-players.mjs.',
    generatedAt: new Date().toISOString(),
    season: SEASON,
    week,
    note,
    players: [],
  };
}

async function main() {
  const week = currentWeek();
  if (week < 1) {
    writeAndLog(emptyOut(0, 'Season has not started — top scorers appear after Week 1.'));
    return;
  }

  const filter = {
    players: {
      filterSlotIds: { value: [0, 2, 4, 6, 17, 16, 23] },
      filterStatsForTopScoringPeriodIds: { value: 2, additionalValue: [`00${SEASON}`, `10${SEASON}`] },
      sortAppliedStatTotalForScoringPeriodId: { sortAsc: false, sortPriority: 1, value: week },
      limit: 60,
      offset: 0,
    },
  };

  const url = `https://lm-api-reads.fantasy.espn.com/apis/v3/games/ffl/seasons/${SEASON}/segments/0/leagues/${LEAGUE_ID}?view=kona_player_info`;
  const res = await fetch(url, { headers: { ...HEADERS, 'x-fantasy-filter': JSON.stringify(filter) } });
  if (!res.ok) throw new Error(`kona_player_info ${res.status}`);
  const j = await res.json();

  const rows = [];
  for (const entry of j.players || []) {
    const p = entry.player || entry;
    const wk = (p.stats || []).find(
      (s) => s.scoringPeriodId === week && s.statSourceId === 0 && s.statSplitTypeId === 1,
    );
    if (!wk || wk.appliedTotal == null) continue;
    rows.push({
      name: p.fullName,
      team: PRO_TEAM[p.proTeamId] ?? 'FA',
      pos: POSITION[p.defaultPositionId] || '?',
      points: Number(wk.appliedTotal.toFixed(1)),
    });
  }
  rows.sort((a, b) => b.points - a.points);

  const out = emptyOut(week, rows.length ? '' : 'No scoring data yet for this week.');
  out.players = rows.slice(0, 10);
  writeAndLog(out);
}

function writeAndLog(out) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(`✓ top-players.json — week ${out.week}, ${out.players.length} players`);
}

main().catch((e) => { console.error('fetch-top-players failed:', e.message); process.exitCode = 1; });
